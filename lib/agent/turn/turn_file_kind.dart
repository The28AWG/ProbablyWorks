/// Как ход агента затронул путь на Host.
enum TurnFileKind {
  /// Файла не было до первой записи в этом ходе; откат — удалить.
  created,

  /// Файл уже существовал; откат — вернуть снимок до первого касания.
  modified,

  /// Файл удалён в ходе (через инструменты, не через shell); откат — восстановить снимок.
  deleted,
}
