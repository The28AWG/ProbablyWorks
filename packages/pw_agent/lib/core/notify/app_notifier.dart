/// Событие агента, о котором нужно сообщить системным уведомлением.
/// Текст строится из типа, а не передаётся готовым: так заголовок и тело переводятся
/// на язык интерфейса в одном месте.
enum AgentNoticeKind {
  /// Ход ждёт решения пользователя по действию (approve/deny).
  approvalNeeded,

  /// Агент задал вопрос и ждёт ответа.
  questionAsked,

  /// Ход завершился штатно.
  turnFinished,

  /// Ход завершился ошибкой.
  turnFailed,

  /// Достигнут лимит шагов: ход приостановлен до действия пользователя.
  stepLimitReached,

  /// Исчерпан бюджет хода: токены, стоимость или время.
  turnBudgetReached,

  /// Агент перестал продвигаться: повторяет действия без нового результата.
  progressStalled,

  /// Наступил срок «напомнить позже»: отложенный чат снова ждёт внимания.
  snoozeDue,

  /// Закончилась общая пауза уведомлений: накопилось то, о чём стоит сказать
  /// одним дайджестом, а не пачкой запоздавших уведомлений.
  attentionDigest,

  /// Фоновая команда завершилась; её результат передан агенту.
  backgroundFinished,
}

/// Устойчивый id системного уведомления.
///
/// Один и тот же ключ означает одно и то же уведомление: повторный показ
/// обновляет запись в трее, а [AppNotifier.cancel] убирает её. Поэтому
/// закрытая карточка не оставляет кнопку на уже неактуальное действие, а
/// событие, пришедшее из двух окон, не превращается в две одинаковые строки.
///
/// Для карточек ключ строится по id карточки: он уникален и приходит в
/// событиях закрытия. Для событий хода — по чату и типу: новое завершение
/// хода в том же чате заменяет предыдущее уведомление, а не копится в трее.
/// События, которые повторяются в одном чате и несут разный смысл (завершение
/// конкретной фоновой команды), различаются [eventId]: иначе следующая команда
/// стёрла бы уведомление о предыдущей.
///
/// [scope] отделяет уведомления разных профилей: id карточек уникальны на
/// сервере, но два демона могут выдать одинаковые значения. Пустой scope
/// означает локального агента: у встроенного профиля соседей нет.
String agentNoticeId({
  required AgentNoticeKind kind,
  String? scope,
  String? chatId,
  String? approvalId,
  String? questionId,
  String? eventId,
}) {
  final prefix = scope == null || scope.isEmpty ? 'local' : scope;
  final cardId = switch (kind) {
    AgentNoticeKind.approvalNeeded => approvalId,
    AgentNoticeKind.questionAsked => questionId,
    _ => null,
  };
  if (cardId != null && cardId.isNotEmpty) {
    return '$prefix:${kind.name}:$cardId';
  }
  if (eventId != null && eventId.isNotEmpty) {
    return '$prefix:${kind.name}:$eventId';
  }
  return '$prefix:${kind.name}:${chatId ?? ''}';
}

/// Ключ группы уведомлений: пара «чат + тип события».
///
/// Пять подтверждений одного чата — это одна группа «Нужно подтверждение» с
/// пятью карточками внутри, а не пять независимых строк в трее. Платформа
/// группирует по этому ключу (`groupKey` на Android, `threadIdentifier` на
/// iOS/macOS), а локальное уведомление дополнительно показывает сводку группы.
///
/// `null` означает, что событие не относится к чату (дайджест, тест relay):
/// такие уведомления не группируются. [scope] отделяет профили так же, как в
/// [agentNoticeId]: одинаковый id чата у двух демонов не должен слипаться.
String? agentNoticeGroupKey({
  required AgentNoticeKind kind,
  String? scope,
  String? chatId,
}) {
  if (chatId == null || chatId.isEmpty) return null;
  final prefix = scope == null || scope.isEmpty ? 'local' : scope;
  return '$prefix:${kind.name}:$chatId';
}

/// Идентификатор ответа, отправленного прямо из уведомления.
///
/// Повторная доставка действия (запуск приложения из уведомления, повтор
/// нажатия после таймаута) несёт тот же ключ, поэтому сервер не создаёт второй
/// ответ на уже закрытый вопрос. Ключ выводится из id вопроса: один вопрос —
/// один ответ, независимо от того, сколько раз платформа повторила действие.
String agentNoticeAnswerId(String questionId) => 'inline:$questionId';

/// Системное уведомление о событии агента. Не показывается, пока окно приложения в фокусе:
/// пользователь и так видит событие в чате.
///
/// Интерфейс живёт в агенте, чтобы headless-демон мог подставить no-op реализацию.
abstract interface class AppNotifier {
  /// [chatTitle] попадает в заголовок, чтобы по уведомлению было видно, какой чат ждёт.
  /// Пустое название допустимо: тогда в заголовке только действие.
  /// [detail] — дополнительные данные события (сейчас только статус фоновой команды).
  ///
  /// [profileId], [chatId], [approvalId] и [questionId] нужны кнопкам
  /// действия: открыть чат, ответить на подтверждение или ответить на вопрос
  /// прямо из уведомления. Локальный агент профиль не знает и передаёт null;
  /// клиент подставляет локальный профиль.
  ///
  /// [noticeId] — устойчивый ключ из [agentNoticeId]. Показ с тем же ключом
  /// обновляет существующее уведомление, а не добавляет второе. Если ключ не
  /// передан, реализация строит его из [kind], [chatId], [approvalId] и
  /// [questionId].
  Future<void> notify({
    required AgentNoticeKind kind,
    required String chatTitle,
    String? detail,
    String? profileId,
    String? chatId,
    String? approvalId,
    String? questionId,
    String? noticeId,
  });

  /// Убирает уведомление с ключом [noticeId] из системного трея.
  ///
  /// Нужен, когда карточку закрыли в любом окне: нажатие на устаревшее
  /// уведомление уже не должно вести к неактуальному действию. Отмена
  /// несуществующего уведомления ничего не делает.
  Future<void> cancel(String noticeId);
}
