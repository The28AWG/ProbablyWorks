/// Уровень, до которого доходит решение по команде.
///
/// Порядок значений — от мягкого к строгому: сравнение по индексу выбирает
/// более осторожный итог.
enum CommandRisk {
  /// Можно выполнить без вопроса.
  auto,

  /// Нужно подтверждение. В режиме авто-подтверждения выполняется.
  ask,

  /// Нельзя выполнить ни в каком режиме политики.
  deny,
}

/// Риск команды и короткая причина для карточки подтверждения и для модели.
class CommandClassification {
  /// Создаёт классификацию.
  const CommandClassification(this.risk, this.reason);

  /// Уровень риска.
  final CommandRisk risk;

  /// Почему выставлен [risk]. На английском: строку читает модель.
  final String reason;
}
