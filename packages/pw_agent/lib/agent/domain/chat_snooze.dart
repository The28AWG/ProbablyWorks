import 'package:equatable/equatable.dart';

/// Отложенное напоминание о чате: «вернусь позже».
///
/// Snooze — это не прочтение и не скрытие чата. Чат остаётся в списке и
/// открывается как обычно; до срока он просто не попадает во входящие и не
/// присылает уведомлений. Срок общий для всех устройств, поэтому хранится в
/// базе агента, а не в настройках окна.
///
/// Запись одна на чат: повторное «напомнить позже» двигает срок, а не копит
/// напоминания. [revision] растёт при каждой записи, чтобы окна отличали
/// свежий срок от запоздавшего снимка.
final class ChatSnooze extends Equatable {
  const ChatSnooze({
    required this.chatId,
    required this.until,
    required this.revision,
  });

  final String chatId;

  /// Момент, до которого чат отложен. Хранится в UTC, сравнивается с текущим
  /// временем без учёта часового пояса устройства.
  final DateTime until;

  final int revision;

  /// Действует ли напоминание в момент [now]. Просроченная запись до очистки
  /// базой уже не скрывает чат: чат должен вернуться, даже если таймер
  /// сработал с задержкой.
  bool isActiveAt(DateTime now) => until.isAfter(now);

  @override
  List<Object?> get props => [chatId, until, revision];
}
