/// Отложенные напоминания о чатах: «напомнить позже».
///
/// Отдельный интерфейс, как дайджест: старые серверы не знают этих
/// маршрутов, и клиент должен показать обычные входящие без действия
/// «Отложить», а не получить ошибку экрана. Встроенный агент реализует
/// интерфейс поверх `ChatAttentionService`, удалённый — поверх
/// `PUT /attention/{chatId}/snooze` и SSE `chatStatusChanged`.
abstract interface class AttentionSnoozeApi {
  /// Умеет ли подключённый агент откладывать напоминания.
  ///
  /// Интерфейс означает, что клиент знает маршруты, но старый демон может их
  /// не иметь. Удалённый клиент узнаёт возможность из снимка входящих: новый
  /// сервер присылает поле `snoozed` даже пустым, старый его не присылает.
  /// До первого снимка и после ответа об отсутствии маршрута (`404 not_found`
  /// или `501 not_supported`) значение false, чтобы интерфейс не обещал
  /// действие, которого сервер не умеет.
  bool get supportsSnooze;

  /// Откладывает напоминание о чате до [until].
  ///
  /// Повторный вызов сдвигает срок. Сервер отклоняет срок в прошлом: иначе
  /// напоминание считалось бы сработавшим в момент создания.
  Future<void> snoozeAttention(String chatId, DateTime until);

  /// Снимает напоминание: чат сразу возвращается во входящие, если там есть
  /// что решать. Идемпотентно.
  Future<void> unsnoozeAttention(String chatId);

  /// Чаты, у которых срок напоминания наступил.
  ///
  /// Событие, а не часть снимка: сам снимок входящих уже вернул чат, а это
  /// уведомление объясняет, почему он снова здесь, и может показать системное
  /// напоминание.
  Stream<String> get attentionDue;
}
