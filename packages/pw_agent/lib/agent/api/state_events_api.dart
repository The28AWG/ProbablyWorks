import 'package:pw_agent/agent/state/shared_state.dart';

/// Поток изменений общих ресурсов, сделанных другим окном или устройством.
///
/// Не входит в [AgentApi], чтобы не расширять все тестовые реализации:
/// встроенный агент работает в одном окне и подписчиков не имеет. Удалённый
/// транспорт реализует интерфейс, а экран проверяет тип источника.
abstract interface class StateEventsApi {
  /// Изменённые ресурсы. Клиент перечитывает снимок, а не применяет дельту.
  ///
  /// После переподключения поток сообщает обо всех ресурсах: события,
  /// пропущенные во время обрыва, догоняются перечитыванием.
  Stream<SharedResource> get sharedStateChanges;
}
