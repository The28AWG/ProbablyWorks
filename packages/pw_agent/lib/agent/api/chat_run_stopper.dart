/// Действия хаба, которые нужны удалению чата.
///
/// Отдельный порт нужен очистке истории: она удаляет строки базы и файлы,
/// но не должна знать про AgentHub и его сессии. В тестах достаточно
/// заглушки, которая ничего не делает.
abstract interface class ChatRunStopper {
  /// Останавливает ход, если он идёт. Чата может не быть в памяти — это не ошибка.
  Future<void> stopChat(String chatId);

  /// Сообщает открытому экрану, что чат удалён. Чата может не быть в памяти:
  /// тогда сообщать некому, и это не ошибка.
  void notifyChatDeleted(String chatId);
}
